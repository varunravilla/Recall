import assert from "node:assert/strict";
import { MongoMemoryServer } from "mongodb-memory-server";
import { createGateway } from "@mit-sdg/sync-engine/boundary";
import { createPhotoHandler } from "../src/photos/http.ts";
import { geminiConfig } from "../src/photos/config.ts";
const mongo = await MongoMemoryServer.create();
process.env.MONGODB_URL = mongo.getUri("recall-live-batch-test");
const { assembleApplication } = await import("../src/assembly.ts");
const { client } = await import("../src/db.ts");
try {
  await client.connect();
  const gateway = createGateway({ application: assembleApplication() });
  const api = createPhotoHandler({ gateway });
  const account = await gateway.invoke("/recall/register", { username: "batch_fixture_user", password: "temporary-fixture-password" });
  assert(account.ok, "Fixture registration failed");
  const session = (account.value as { session: string }).session;
  const future = await Bun.file(new URL("../tests/fixtures/future-concert.png", import.meta.url)).arrayBuffer();
  const expired = await Bun.file(new URL("../tests/fixtures/expired-concert.png", import.meta.url)).arrayBuffer();
  const form = new FormData();
  form.set("session", session); form.set("timezone", "America/New_York"); form.set("consent", "gemini");
  form.set("ids", JSON.stringify(["future", "expired", "duplicate"]));
  for (const image of [future, expired, future]) form.append("images", new Blob([image], { type: "image/png" }), "synthetic.png");
  const started = performance.now();
  const response = await api(new Request("http://localhost/api/recall/photos/import-batch", { method: "POST", body: form }));
  const result = await response.json() as { error?: string; results: Array<{ id: string; status: string; collection?: string }> };
  assert.equal(response.status, 200, result.error ?? "Batch failed");
  const byId = new Map(result.results.map(r => [r.id, r]));
  assert.equal(byId.get("future")?.status, "added");
  assert.equal(byId.get("expired")?.status, "skipped");
  assert.equal(byId.get("duplicate")?.status, "duplicate");
  const collection = byId.get("future")!.collection;
  const image = await api(new Request("http://localhost/api/recall/photos/image", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ session, collection }) }));
  assert.equal(image.status, 200);
  assert.deepEqual(new Uint8Array(await image.arrayBuffer()), new Uint8Array(future));
  const library = await gateway.invoke("/recall/library/list", { session }); assert(library.ok);
  assert.equal((library.value as { book: { items: unknown[] } }).book.items.length, 1);
  const report = { checkedAt: new Date().toISOString(), status: "PASS", model: geminiConfig().model, elapsedSeconds: Number(((performance.now() - started) / 1000).toFixed(2)), selectedPhotos: 3, uniqueImagesInOneGeminiRequest: 2, outcomes: result.results.map(({ id, status }) => ({ id, status })), savedItemCount: 1, persistedImageMatches: true, note: "Real batch Gemini request + multipart adapter + authored compositions + disposable MongoDB. Synthetic fixtures only. This is not a comparative speed benchmark or browser journey." };
  await Bun.write("docs/validation/batch-live.json", JSON.stringify(report, null, 2) + "\n");
  console.log(JSON.stringify(report, null, 2));
} finally { await client.close(); await mongo.stop(); }
