import { afterAll, beforeAll, expect, test } from "bun:test";
import { CollectingConcept } from "../../src/concepts/Collecting.ts";
import { InterpretingConcept } from "../../src/concepts/Interpreting.ts";
import { RemindingConcept } from "../../src/concepts/Reminding.ts";
import { InvalidTime } from "../../src/input.ts";
import { openTestDb, type TestDb } from "../helpers/db.ts";
let store: TestDb;
beforeAll(async () => { store = await openTestDb(); }, 120000);
afterAll(async () => { await store?.close(); });
test("invalid timestamps are refused by concepts without storing or changing records", async () => {
  const collecting = new CollectingConcept(store.db);
  const interpreting = new InterpretingConcept(store.db);
  const reminding = new RemindingConcept(store.db);
  const invalid = new Date(NaN);
  await expect(collecting.add({ user: "u", item: "i", content: "Concert", collectedAt: invalid })).rejects.toBeInstanceOf(InvalidTime);
  await expect(collecting.addPhoto({ user: "u", item: "p", content: "Concert", collectedAt: invalid, imageData: "", mimeType: "image/png" })).rejects.toBeInstanceOf(InvalidTime);
  expect(await collecting._byOwner({ user: "u" })).toEqual([]);
  await expect(interpreting.propose({ item: "i", kind: "event", summary: "Tickets", relevantAt: invalid })).rejects.toBeInstanceOf(InvalidTime);
  expect(await interpreting._byItem({ item: "i" })).toEqual([]);
  const { interpretation } = await interpreting.propose({ item: "valid", kind: "event", summary: "Tickets" });
  const before = await interpreting._byId({ interpretation });
  await expect(interpreting.revise({ interpretation, kind: "event", summary: "Changed", relevantAt: invalid })).rejects.toBeInstanceOf(InvalidTime);
  expect(await interpreting._byId({ interpretation })).toEqual(before);
  await expect(reminding.schedule({ user: "u", item: "t", at: invalid })).rejects.toBeInstanceOf(InvalidTime);
  expect(await reminding._byItem({ user: "u", item: "t" })).toEqual([]);
  const at = new Date("2030-01-01T12:00:00Z");
  const { reminder } = await reminding.schedule({ user: "u", item: "t", at });
  await expect(reminding.reschedule({ user: "u", reminder, at: invalid })).rejects.toBeInstanceOf(InvalidTime);
  expect((await reminding._byItem({ user: "u", item: "t" }))[0]?.at).toEqual(at);
});
